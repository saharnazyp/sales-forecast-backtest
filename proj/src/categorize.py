import pandas as pd, numpy as np, re

def normalize_fa(s):
    if not isinstance(s,str): return ""
    s = s.replace('\u200c',' ')
    # arabic -> persian
    for a,b in [('ي','ی'),('ك','ک'),('ٔ',''),('أ','ا'),('إ','ا'),('آ','ا'),
                ('ة','ه'),('ۀ','ه'),('ؤ','و'),('ء','')]:
        s = s.replace(a,b)
    s = re.sub(r'[ًٌٍَُِّْ]','',s)          # diacritics
    s = re.sub(r'[*#\(\)\[\]\-_/\\.,،؛:]',' ',s)
    s = re.sub(r'\d+','',s)
    s = re.sub(r'\s+',' ',s).strip()
    return s

